// assignmentGroupRead is the bindings-service method that reads a group's
// assignment for the policy type (default "GroupPolicyAssignment").
func (r Resource) assignmentGroupRead() string {
	if r.AssignmentGroupRead != "" {
		return r.AssignmentGroupRead
	}
	return "GroupPolicyAssignment"
}

// assignmentGroupCount is the bindings-service method that counts the group
// assignments of the policy type (default "GroupPolicyAssignmentCount").
func (r Resource) assignmentGroupCount() string {
	if r.AssignmentGroupCount != "" {
		return r.AssignmentGroupCount
	}
	return "GroupPolicyAssignmentCount"
}

// grantGroupField is the grant op's params field that carries the target group
// (default "Group").
func (r Resource) grantGroupField() string {
	if r.Create.IdentityField != "" {
		return r.Create.IdentityField
	}
	return "Group"
}

// genGroupAssignmentResource emits a group policy-assignment resource (see
// Resource.AssignmentGroup): group_id + policy_name + rank over the
// Grant-Cs<Type> -Group grant. Unlike the per-user variant, a write that never
// becomes visible fails the apply instead of storing an unapplied rank. It is
// self-contained (mirrors genAssignmentResource).
func genGroupAssignmentResource(cfg Config, r Resource) ([]byte, error) {
	var b bytes.Buffer
	recv := r.recv()
	model := r.model()
	svc := "r.client." + cfg.ClientField
	pkg := cfg.BindingsPkg
	grant := r.Create.Method          // e.g. "GrantCsTeamsMeetingPolicy"
	grantP := r.Create.Params         // e.g. "GrantCsTeamsMeetingPolicyParams"
	groupField := r.grantGroupField() // grant params field for the group, e.g. "Group"
	ptype := r.AssignmentPolicyType
	readFn := r.assignmentGroupRead()
	countFn := r.assignmentGroupCount()
	grantCmdlet := r.grantCmdlet()
	mu, wait, uuid, seen := recv+"Mu", recv+"Wait", recv+"UUID", recv+"Seen"
	const readErr = "reading the group policy assignment failed"

	fmt.Fprintf(&b, "// Code generated by gen-tf; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", cfg.Package)

	// Imports — exactly what the body references.
	fmt.Fprintf(&b, "import (\n")
	for _, imp := range []string{"context", "fmt", "regexp", "strings", "sync", "time"} {
		fmt.Fprintf(&b, "\t%q\n", imp)
	}
	fmt.Fprintf(&b, "\n")
	for _, imp := range []string{"diag", "path", "resource", "resource/schema", "resource/schema/planmodifier", "resource/schema/stringplanmodifier", "types"} {
		fmt.Fprintf(&b, "\t%q\n", "github.com/hashicorp/terraform-plugin-framework/"+imp)
	}
	fmt.Fprintf(&b, "\n")
	fmt.Fprintf(&b, "\t%q\n", "github.com/terraprovider/go-msadmin/consistency")
	fmt.Fprintf(&b, "\t%q\n", cfg.BindingsImport)
	fmt.Fprintf(&b, "\t%q\n", cfg.ClientsImport)
	fmt.Fprintf(&b, "\t%q\n", "github.com/terraprovider/tf-msadmin/resourcex")
	fmt.Fprintf(&b, ")\n\n")

	// Interface asserts + package state + type + constructor.
	fmt.Fprintf(&b, "var (\n")
	for _, i := range []string{"Resource", "ResourceWithConfigure", "ResourceWithImportState", "ResourceWithValidateConfig"} {
		fmt.Fprintf(&b, "\t_ resource.%s = &%s{}\n", i, recv)
	}
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// %s serializes this policy type's group assignments per tenant within the\n", mu)
	fmt.Fprintf(&b, "// provider process (tenant id -> *sync.Mutex): Teams keeps ranks dense per\n")
	fmt.Fprintf(&b, "// policy type, so concurrent writes renumber each other and a read during a\n")
	fmt.Fprintf(&b, "// write sees a transient rank.\n")
	fmt.Fprintf(&b, "var %s sync.Map\n\n", mu)
	fmt.Fprintf(&b, "// %s is the poll budget for a write to become visible. Group grants showed\n", wait)
	fmt.Fprintf(&b, "// up on the first read (2-5 s) in live tests; a variable so tests can shorten it.\n")
	fmt.Fprintf(&b, "var %s = consistency.Config{Attempts: 20, Delay: 4 * time.Second}\n\n", wait)
	fmt.Fprintf(&b, "var %s = regexp.MustCompile(`^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$`)\n\n", uuid)
	fmt.Fprintf(&b, "type %s struct{ client *clients.Client }\n\n", recv)
	fmt.Fprintf(&b, "// %s is one read of the group's assignment (name == \"\" means none).\n", seen)
	fmt.Fprintf(&b, "type %s struct {\n\tname string\n\trank int64\n}\n\n", seen)
	fmt.Fprintf(&b, "// %s manages the assignment of a %s instance to an Entra group (%s -Group).\n", r.ctor(), ptype, grantCmdlet)
	fmt.Fprintf(&b, "func %s() resource.Resource { return &%s{} }\n\n", r.ctor(), recv)

	// Model.
	fmt.Fprintf(&b, "type %s struct {\n", model)
	fmt.Fprintf(&b, "\tID types.String `tfsdk:\"id\"`\n")
	fmt.Fprintf(&b, "\tGroupID types.String `tfsdk:\"group_id\"`\n")
	fmt.Fprintf(&b, "\tPolicyName types.String `tfsdk:\"policy_name\"`\n")
	fmt.Fprintf(&b, "\tRank types.Int64 `tfsdk:\"rank\"`\n")
	fmt.Fprintf(&b, "}\n\n")

	// Metadata.
	fmt.Fprintf(&b, "func (r *%s) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {\n", recv)
	fmt.Fprintf(&b, "\tresp.TypeName = req.ProviderTypeName + %q\n}\n\n", "_"+r.TFName)

	// Schema.
	fmt.Fprintf(&b, "func (r *%s) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {\n", recv)
	fmt.Fprintf(&b, "\tresp.Schema = schema.Schema{\n")
	fmt.Fprintf(&b, "\t\tDescription: %q,\n", r.Description)
	fmt.Fprintf(&b, "\t\tAttributes: map[string]schema.Attribute{\n")
	fmt.Fprintf(&b, "\t\t\t%q: schema.StringAttribute{Computed: true, Description: %q, PlanModifiers: []planmodifier.String{stringplanmodifier.UseStateForUnknown()}},\n",
		"id", "Assignment identifier (the group's object id).")
	fmt.Fprintf(&b, "\t\t\t%q: schema.StringAttribute{Required: true, Description: %q, PlanModifiers: []planmodifier.String{stringplanmodifier.RequiresReplace()}},\n",
		"group_id", "Object id of the Entra group the policy is assigned to. Changing it forces replacement.")
	fmt.Fprintf(&b, "\t\t\t%q: schema.StringAttribute{Required: true, Description: %q},\n",
		"policy_name", "Name of the "+ptype+" instance to assign to the group.")
	fmt.Fprintf(&b, "\t\t\t%q: schema.Int64Attribute{Required: true, Description: %q},\n",
		"rank", "One-based rank among the group assignments of "+ptype+"; a user in several groups gets the policy of the lowest rank. Teams keeps ranks dense: assigning another group at an occupied rank shifts this one, which shows up as drift. A rank beyond the number of group assignments is placed last: the apply warns and the difference shows up as drift until the lower ranks exist, and an apply warns again while the rank stays beyond that number.")
	fmt.Fprintf(&b, "\t\t},\n\t}\n}\n\n")

	// Configure.
	fmt.Fprintf(&b, "func (r *%s) Configure(_ context.Context, req resource.ConfigureRequest, _ *resource.ConfigureResponse) {\n", recv)
	fmt.Fprintf(&b, "\tif req.ProviderData == nil {\n\t\treturn\n\t}\n")
	fmt.Fprintf(&b, "\tr.client = req.ProviderData.(*clients.Client)\n}\n\n")

	// ValidateConfig: the framework-validators module is not a dependency.
	fmt.Fprintf(&b, "func (r *%s) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {\n", recv)
	fmt.Fprintf(&b, "\tvar cfg %s\n", model)
	fmt.Fprintf(&b, "\tresp.Diagnostics.Append(req.Config.Get(ctx, &cfg)...)\n")
	fmt.Fprintf(&b, "\tif resp.Diagnostics.HasError() {\n\t\treturn\n\t}\n")
	fmt.Fprintf(&b, "\tif v := cfg.GroupID; !v.IsNull() && !v.IsUnknown() && !%s.MatchString(v.ValueString()) {\n", uuid)
	fmt.Fprintf(&b, "\t\tresp.Diagnostics.AddAttributeError(path.Root(%q), %q, %q)\n\t}\n", "group_id", "Invalid group_id", "group_id must be the object id (UUID) of an Entra group.")
	fmt.Fprintf(&b, "\tif v := cfg.PolicyName; !v.IsNull() && !v.IsUnknown() && v.ValueString() == \"\" {\n")
	fmt.Fprintf(&b, "\t\tresp.Diagnostics.AddAttributeError(path.Root(%q), %q, %q)\n\t}\n", "policy_name", "Invalid policy_name", "policy_name must not be empty.")
	fmt.Fprintf(&b, "\tif v := cfg.Rank; !v.IsNull() && !v.IsUnknown() && v.ValueInt64() < 1 {\n")
	fmt.Fprintf(&b, "\t\tresp.Diagnostics.AddAttributeError(path.Root(%q), %q, %q)\n\t}\n}\n\n", "rank", "Invalid rank", "rank is one-based and must be at least 1.")

	// Create / Update share assign. Create saves the state once the grant went
	// through, even if the wait then fails: Terraform taints the resource
	// instead of losing track of a grant that exists in Teams. A failed Update
	// keeps the prior state, which the next refresh corrects.
	for _, op := range []string{"Create", "Update"} {
		fmt.Fprintf(&b, "func (r *%s) %s(ctx context.Context, req resource.%sRequest, resp *resource.%sResponse) {\n", recv, op, op, op)
		fmt.Fprintf(&b, "\tvar plan %s\n", model)
		fmt.Fprintf(&b, "\tresp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)\n")
		fmt.Fprintf(&b, "\tif resp.Diagnostics.HasError() {\n\t\treturn\n\t}\n")
		if op == "Create" {
			fmt.Fprintf(&b, "\t// Saved even when the wait fails, so Terraform taints the resource\n")
			fmt.Fprintf(&b, "\t// instead of losing track of the grant.\n")
			fmt.Fprintf(&b, "\tif granted, _ := r.assign(ctx, &plan, &resp.Diagnostics); granted {\n")
		} else {
			fmt.Fprintf(&b, "\tif _, ok := r.assign(ctx, &plan, &resp.Diagnostics); ok {\n")
		}
		fmt.Fprintf(&b, "\t\tresp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)\n\t}\n}\n\n")
	}

	// Read.
	fmt.Fprintf(&b, "func (r *%s) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {\n", recv)
	fmt.Fprintf(&b, "\tvar state %s\n", model)
	fmt.Fprintf(&b, "\tresp.Diagnostics.Append(req.State.Get(ctx, &state)...)\n")
	fmt.Fprintf(&b, "\tif resp.Diagnostics.HasError() {\n\t\treturn\n\t}\n")
	fmt.Fprintf(&b, "\tdefer r.lock()()\n")
	fmt.Fprintf(&b, "\tgroup := state.GroupID.ValueString()\n")
	fmt.Fprintf(&b, "\tgot, err := r.read(ctx, group)\n")
	fmt.Fprintf(&b, "\tif err != nil {\n\t\tresp.Diagnostics.AddError(%q, err.Error())\n\t\treturn\n\t}\n", readErr)
	// Empty ⇒ no assignment (unassigned or the group was deleted): drift.
	fmt.Fprintf(&b, "\tif got.name == \"\" {\n\t\tresp.State.RemoveResource(ctx)\n\t\treturn\n\t}\n")
	fmt.Fprintf(&b, "\t// The API compares names case-insensitively; keep the configured spelling.\n")
	fmt.Fprintf(&b, "\tif !strings.EqualFold(state.PolicyName.ValueString(), got.name) {\n\t\tstate.PolicyName = types.StringValue(got.name)\n\t}\n")
	fmt.Fprintf(&b, "\tstate.Rank = types.Int64Value(got.rank)\n")
	fmt.Fprintf(&b, "\tstate.ID = types.StringValue(group)\n")
	fmt.Fprintf(&b, "\tresp.Diagnostics.Append(resp.State.Set(ctx, &state)...)\n}\n\n")

	// Delete: unassign (no PolicyName ⇒ {"policyName": null}) and wait until gone.
	fmt.Fprintf(&b, "func (r *%s) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {\n", recv)
	fmt.Fprintf(&b, "\tvar state %s\n", model)
	fmt.Fprintf(&b, "\tresp.Diagnostics.Append(req.State.Get(ctx, &state)...)\n")
	fmt.Fprintf(&b, "\tif resp.Diagnostics.HasError() {\n\t\treturn\n\t}\n")
	fmt.Fprintf(&b, "\tdefer r.lock()()\n")
	fmt.Fprintf(&b, "\tgroup := state.GroupID.ValueString()\n")
	fmt.Fprintf(&b, "\tif _, err := %s.%s(ctx, %s.%s{%s: group}); err != nil {\n", svc, grant, pkg, grantP, groupField)
	fmt.Fprintf(&b, "\t\tif !isNotFound(err) {\n\t\t\tresp.Diagnostics.AddError(%q, err.Error())\n\t\t}\n\t\treturn\n\t}\n", grantCmdlet+" -Group (unassign) failed")
	fmt.Fprintf(&b, "\tif _, ok, err := r.waitFor(ctx, group, func(s %s) bool { return s.name == \"\" }); err != nil {\n", seen)
	fmt.Fprintf(&b, "\t\tresp.Diagnostics.AddError(%q, err.Error())\n", readErr)
	fmt.Fprintf(&b, "\t} else if !ok {\n")
	fmt.Fprintf(&b, "\t\tresp.Diagnostics.AddError(%q, %q)\n\t}\n}\n\n",
		"group policy assignment was not removed", "Teams still reports the group's assignment after the unassign.")

	// ImportState: the import id is the group id; id and group_id both take it.
	fmt.Fprintf(&b, "func (r *%s) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {\n", recv)
	fmt.Fprintf(&b, "\tresp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root(%q), req.ID)...)\n", "id")
	fmt.Fprintf(&b, "\tresp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root(%q), req.ID)...)\n}\n\n", "group_id")

	// lock takes this policy type's lock for the client's tenant and returns
	// the unlock.
	fmt.Fprintf(&b, "func (r *%s) lock() func() {\n", recv)
	tenant := `""`
	if cfg.TenantField != "" {
		tenant = "r.client." + cfg.TenantField
	}
	fmt.Fprintf(&b, "\tm, _ := %s.LoadOrStore(%s, &sync.Mutex{})\n", mu, tenant)
	fmt.Fprintf(&b, "\tmu := m.(*sync.Mutex)\n")
	fmt.Fprintf(&b, "\tmu.Lock()\n")
	fmt.Fprintf(&b, "\treturn mu.Unlock\n}\n\n")

	// assign grants the planned instance at the planned rank and waits until the
	// read reports both. Teams accepts any rank but places one beyond the number
	// of group assignments of the type last (live-verified); that is a warning,
	// not an error, so a configuration whose lower ranks are created later in
	// the same apply (Terraform picks the order) converges on the next run.
	// The rank Teams will use is computed from the count read before the grant:
	// the group's own read cannot tell a placed-last result that equals the
	// pre-grant state (a move beyond the count) from a grant that has not
	// propagated yet.
	fmt.Fprintf(&b, "// assign grants the planned policy at the planned rank and waits until the read\n")
	fmt.Fprintf(&b, "// reports both. granted: the grant call succeeded; ok: the result was confirmed.\n")
	fmt.Fprintf(&b, "func (r *%s) assign(ctx context.Context, plan *%s, diags *diag.Diagnostics) (granted, ok bool) {\n", recv, model)
	fmt.Fprintf(&b, "\tdefer r.lock()()\n")
	fmt.Fprintf(&b, "\tgroup := plan.GroupID.ValueString()\n")
	fmt.Fprintf(&b, "\twant := plan.PolicyName.ValueString()\n")
	fmt.Fprintf(&b, "\trank := plan.Rank.ValueInt64()\n")
	fmt.Fprintf(&b, "\tplan.ID = types.StringValue(group)\n")
	fmt.Fprintf(&b, "\tbefore, err := r.read(ctx, group)\n")
	fmt.Fprintf(&b, "\tif err != nil {\n\t\tdiags.AddError(%q, err.Error())\n\t\treturn false, false\n\t}\n", readErr)
	fmt.Fprintf(&b, "\tcount, err := %s.%s(ctx, %q)\n", svc, countFn, ptype)
	fmt.Fprintf(&b, "\tif err != nil {\n\t\tdiags.AddError(%q, err.Error())\n\t\treturn false, false\n\t}\n", "counting the group policy assignments failed")
	fmt.Fprintf(&b, "\t// clamp is the rank Teams uses: it honours a rank up to the number of group\n")
	fmt.Fprintf(&b, "\t// assignments of the type, one more for a group that has none yet, and\n")
	fmt.Fprintf(&b, "\t// places a higher one last. The group's own rank bounds a count that lags\n")
	fmt.Fprintf(&b, "\t// a recent insert.\n")
	fmt.Fprintf(&b, "\tclamp := func(count int64) int64 {\n")
	fmt.Fprintf(&b, "\t\tslots := max(count, before.rank)\n")
	fmt.Fprintf(&b, "\t\tif before.name == \"\" {\n\t\t\tslots = count + 1\n\t\t}\n")
	fmt.Fprintf(&b, "\t\treturn min(rank, slots)\n\t}\n")
	fmt.Fprintf(&b, "\texpected := clamp(count)\n")
	fmt.Fprintf(&b, "\tif _, err := %s.%s(ctx, %s.%s{%s: group, PolicyName: want, Rank: &rank}); err != nil {\n", svc, grant, pkg, grantP, groupField)
	fmt.Fprintf(&b, "\t\tdiags.AddError(%q, err.Error())\n\t\treturn false, false\n\t}\n", grantCmdlet+" -Group failed")
	fmt.Fprintf(&b, "\t// The wait accepts the requested rank and the expected one. If the count\n")
	fmt.Fprintf(&b, "\t// was stale, another lower rank is accepted as placed last, but only when\n")
	fmt.Fprintf(&b, "\t// it differs from the pre-grant read, because a stale read repeats that.\n")
	fmt.Fprintf(&b, "\tplacedLast := func(s %s) bool {\n", seen)
	fmt.Fprintf(&b, "\t\treturn strings.EqualFold(s.name, want) && s.rank < rank && !(strings.EqualFold(s.name, before.name) && s.rank == before.rank)\n")
	fmt.Fprintf(&b, "\t}\n")
	fmt.Fprintf(&b, "\tgot, ok, err := r.waitFor(ctx, group, func(s %s) bool {\n", seen)
	fmt.Fprintf(&b, "\t\treturn strings.EqualFold(s.name, want) && (s.rank == rank || s.rank == expected) || placedLast(s)\n")
	fmt.Fprintf(&b, "\t})\n")
	fmt.Fprintf(&b, "\tif err != nil {\n\t\tdiags.AddError(%q, err.Error())\n\t\treturn true, false\n\t}\n", readErr)
	fmt.Fprintf(&b, "\tif !ok && strings.EqualFold(got.name, want) && got.rank < rank {\n")
	fmt.Fprintf(&b, "\t\t// A count that lagged a removal expects too high a rank, and the result\n")
	fmt.Fprintf(&b, "\t\t// can equal the pre-grant read, which placedLast rejects: count again.\n")
	fmt.Fprintf(&b, "\t\tif n, err := %s.%s(ctx, %q); err == nil && got.rank == clamp(n) {\n\t\t\tok = true\n\t\t}\n\t}\n", svc, countFn, ptype)
	fmt.Fprintf(&b, "\tif !ok {\n")
	fmt.Fprintf(&b, "\t\tdiags.AddError(%q, fmt.Sprintf(%q, got.name, got.rank, want, rank, expected, count))\n\t\treturn true, false\n\t}\n",
		"group policy assignment did not reach the requested state",
		"After "+grantCmdlet+" -Group, Teams reports policy %q at rank %d; requested %q at rank %d, expected at rank %d of %d "+ptype+" group assignments before the grant. The grant was not confirmed on consecutive reads.")
	fmt.Fprintf(&b, "\tif got.rank != rank {\n")
	fmt.Fprintf(&b, "\t\tdiags.AddAttributeWarning(path.Root(%q), %q, fmt.Sprintf(%q, got.rank, rank, rank))\n\t}\n", "rank", "Rank placed last",
		"Teams reports the assignment at rank %d instead of %d. Teams places a rank beyond the number of "+ptype+" group assignments last. The next refresh shows the difference as drift, and an apply sets rank %d once the lower ranks exist.")
	fmt.Fprintf(&b, "\treturn true, true\n}\n\n")

	// read is the single read helper call.
	fmt.Fprintf(&b, "func (r *%s) read(ctx context.Context, group string) (%s, error) {\n", recv, seen)
	fmt.Fprintf(&b, "\tname, rank, err := %s.%s(ctx, group, %q)\n", svc, readFn, ptype)
	fmt.Fprintf(&b, "\treturn %s{name, rank}, err\n}\n\n", seen)

	// waitFor polls until done holds for the same state on
	// resourcex.ReflectedReads consecutive reads and returns the last read and
	// whether it did. It counts the streak itself (consistency.RetryUntil
	// rather than resourcex.LoadUntil): a different state that also satisfies
	// done (the requested rank vs. placed last) starts its own streak, and a
	// single matching read at the end of the budget is not enough. An empty
	// name is a state (unassigned), not "not yet visible", so every read
	// counts as present.
	fmt.Fprintf(&b, "// waitFor polls until done holds for the same state on resourcex.ReflectedReads\n")
	fmt.Fprintf(&b, "// consecutive reads and returns the last read and whether it did.\n")
	fmt.Fprintf(&b, "func (r *%s) waitFor(ctx context.Context, group string, done func(%s) bool) (%s, bool, error) {\n", recv, seen, seen)
	fmt.Fprintf(&b, "\tvar last, prev %s\n", seen)
	fmt.Fprintf(&b, "\tstreak := 0\n")
	fmt.Fprintf(&b, "\t_, ok, err := consistency.RetryUntil(ctx, %s, func(ctx context.Context) (%s, bool, error) {\n", wait, seen)
	fmt.Fprintf(&b, "\t\ts, err := r.read(ctx, group)\n")
	fmt.Fprintf(&b, "\t\tlast = s\n")
	fmt.Fprintf(&b, "\t\treturn s, true, err\n")
	fmt.Fprintf(&b, "\t}, func(s %s) bool {\n", seen)
	fmt.Fprintf(&b, "\t\tswitch {\n")
	fmt.Fprintf(&b, "\t\tcase !done(s):\n\t\t\tstreak = 0\n\t\t\treturn false\n")
	fmt.Fprintf(&b, "\t\tcase streak > 0 && !(strings.EqualFold(s.name, prev.name) && s.rank == prev.rank):\n")
	fmt.Fprintf(&b, "\t\t\tstreak = 1 // another state that satisfies done starts its own streak\n")
	fmt.Fprintf(&b, "\t\tdefault:\n\t\t\tstreak++\n\t\t}\n")
	fmt.Fprintf(&b, "\t\tprev = s\n")
	fmt.Fprintf(&b, "\t\treturn streak >= resourcex.ReflectedReads\n")
	fmt.Fprintf(&b, "\t})\n")
	fmt.Fprintf(&b, "\treturn last, ok, err\n}\n")

	return gofmt(b.String())
}
